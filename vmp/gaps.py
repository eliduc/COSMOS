# -*- coding: utf-8 -*-
"""Этап 2 переноса ВМП: пробелы шаблонов — извещение и маршрут.

Поручение владельца (2026-08-27, узел vmp-boundary): «Если в ВМП есть
правила или критерии оптимизации, под которые в COSMOS нет шаблонов
(паттернов), об этом извещается пользователь и, по его отмашке,
с помощью LLM реализуется этот шаблон».

Инвариант границы: любой отказ приёмной части — пробел расчётного слоя
COSMOS; ВМП по определению полна (лист 01 переноса, п. 1). Отсюда два
законных маршрута пробела и ни одного молчаливого:

  stop (умолчание) — VmpGapStop с поимённым перечнем: полнота ВМП —
      инвариант, расчёт без объявленной цели не запускается;
  warn — расчёт продолжается только по известным целевым, извещение
      отдаётся вызывающей стороне для показа пользователю.

Куда пробел уходит дальше — решает КЛАССИФИКАТОР ЗАЯВОК КАТАЛОГА
(`vmp.catalog_requests.classify`, шаг 6): пробел относительно записи
каталога становится заявкой на вид исполнителя, пробел без записи —
заявкой на новую запись из CDPM либо вручную, всё прочее заявкой
каталога не закрывается и названо словами. Прежний путь «строка
очереди изменений с машинной формой правила» снят вместе с
`rule_gap_to_cr`/`to_cr` (проект шага 6, §3.7): текст правила
авиакомпании в очередь изменений больше не попадает — заявка несёт
раздел, запись и виды.

Этот модуль остаётся сверкой и извещением: он называет пробелы
поимённо и решает, останавливать ли расчёт.
"""
from dataclasses import dataclass

from vmp.criteria import CriterionGap

ON_GAP_CHOICES = ("stop", "warn")


@dataclass(frozen=True)
class RuleGap:
    """Правило ВМП без шаблона-исполнителя в COSMOS.

    Источник — предпрогонный отчёт покрытия решателя (Ш-1п кнопки):
    reason называет корзину (отказ компилятора / вне жёсткого
    исполнения / мягкое без исполнителя); rule — машинная форма
    правила из модели пакета (id, title, statement, zone, kind,
    sources), она едет в заявку целиком — LLM-дописывание шаблона
    работает от первоисточника, не от пересказа."""
    rule_id: str
    reason: str
    rule: dict | None


def rule_gaps(uncovered: list[dict], model: dict) -> list[RuleGap]:
    """Сверка ВМП с шаблонами: перечень непокрытых правил отчёта
    покрытия обогащается машинной формой правила из модели пакета.
    Правило, которого в модели нет, — тоже пробел, но с rule=None
    и громкой пометкой в reason (брак согласованности пакета)."""
    by_id = {str(r.get("id")): r for r in (model.get("rules") or [])}
    out = []
    for u in uncovered or []:
        rid = str(u.get("rule_id"))
        rule = by_id.get(rid)
        reason = str(u.get("reason") or "исполнитель не найден")
        if rule is None:
            reason += ("; ВНИМАНИЕ: правила нет в модели пакета — "
                       "брак согласованности отчёта покрытия и ВМП")
        out.append(RuleGap(rule_id=rid, reason=reason, rule=rule))
    return out


def notify_rules_text(gaps: list[RuleGap]) -> str:
    """Извещение пользователю о правилах без шаблонов — поимённо:
    правило, причина, чем закрывается (поручение владельца
    2026-08-27/28: известить и по отмашке дописать шаблон LLM)."""
    lines = [f"правил ВМП без шаблона-исполнителя COSMOS: {len(gaps)}"]
    for g in gaps:
        title = (g.rule or {}).get("title") or "без заголовка"
        lines.append(
            f"- {g.rule_id} ({title}): {g.reason}; закрывается заявкой "
            f"каталога шаблонов — вид заявки называет классификатор "
            f"нажатия (заявка на вид исполнителя, новая запись либо "
            f"правка записи)")
    return "\n".join(lines)


class VmpGapStop(RuntimeError):
    """Остановка по пробелу шаблона (--on-gap=stop, умолчание)."""

    def __init__(self, gaps: list[CriterionGap]):
        self.gaps = list(gaps)
        super().__init__(notify_text(self.gaps))


def notify_text(gaps: list[CriterionGap]) -> str:
    """Извещение пользователю: поимённо — вид, источник в ВМП, чего
    не хватает, чем закрывается."""
    lines = [f"пробелы шаблонов COSMOS: {len(gaps)}"]
    for g in gaps:
        src = g.source_rule or "источник в ВМП не назван"
        lines.append(
            f"- вид '{g.kind}' ({g.title}); правило: {src}; "
            f"{g.needs}; закрывается заявкой каталога шаблонов — "
            f"вид заявки называет классификатор нажатия")
    return "\n".join(lines)


def route(gaps: list[CriterionGap], on_gap: str = "stop") -> str:
    """Маршрут пробелов. stop → VmpGapStop; warn → текст извещения
    (вызывающая сторона показывает его пользователю и продолжает
    только по известным целевым). Пустой список — пустая строка."""
    if on_gap not in ON_GAP_CHOICES:
        raise ValueError(
            f"on_gap {on_gap!r} вне перечня {ON_GAP_CHOICES}")
    if not gaps:
        return ""
    if on_gap == "stop":
        raise VmpGapStop(gaps)
    return notify_text(gaps)

/** Explicitly selected, offline component probe, NOT a stand/admission PASS.
 * Inputs are generated by the real Python exporter/world_to_problem from the
 * unchanged native catalogue. No package permission, support or oracle is
 * edited here. The first test preserves the actual admission refusal. The
 * second intentionally diagnoses the score component below that gate, without
 * solve(), HTTP, services or any write to the supplied inputs.
 *
 * Not named *Test: default discovery must not need external input properties.
 */
class A06NativeDutyProbe {
    private val mapper = ObjectMapper().findAndRegisterModules()
    private val constraint = "Max duty period (rest-segmented)"

    private data class Inputs(val pkg: LoadedTaskPackage, val problemBytes: ByteArray,
                              val world: JsonNode)

    private fun sha(bytes: ByteArray): String = MessageDigest.getInstance("SHA-256")
        .digest(bytes).joinToString("") { "%02x".format(it) }

    private fun withInputs(block: (Inputs) -> Unit) {
        val directory = Path.of(requireNotNull(System.getProperty("a06.native.inputs")) {
            "Explicit probe requires -Da06.native.inputs=<isolated input directory>"
        }).toAbsolutePath().normalize()
        val names = listOf("st-duty-1.zip", "st-duty-1.problem.json", "st-duty-1.world.json", "identity.json")
        val bytes = names.associateWith { name -> Files.readAllBytes(directory.resolve(name)) }
        val before = bytes.mapValues { sha(it.value) }
        try {
            val identity = mapper.readTree(bytes.getValue("identity.json"))
            assertEquals("st-duty-1", identity.path("task").asText())
            assertEquals("0.7.0-draft.3", identity.path("catalog_version").asText())
            for (name in names.filter { it != "identity.json" }) {
                assertEquals(identity.path("files").path(name).asText(), before.getValue(name),
                    "Input must match the producer's exact source manifest: $name")
            }
            block(Inputs(TaskPackage.readBytes(bytes.getValue("st-duty-1.zip")),
                bytes.getValue("st-duty-1.problem.json"),
                mapper.readTree(bytes.getValue("st-duty-1.world.json"))))
        } finally {
            assertEquals(before, names.associateWith { sha(Files.readAllBytes(directory.resolve(it))) },
                "Neither diagnostic boundaries nor admission may alter native inputs")
            RunThresholds.clearForTests()
            LastProviderReadings.clearForTests()
        }
    }

    @Test
    fun nativePackageRemainsRefusedByPairingAdmission() = withInputs { input ->
        assertFalse(input.pkg.allowedModes["pairing"].orEmpty().contains("feasibility-hard"))
        val refusal = assertThrows<TaskModeRefused> {
            TaskModes.resolve("feasibility-hard", input.pkg, "pairing")
        }
        assertTrue(refusal.message.orEmpty().contains("allowed_modes="), refusal.message)
        assertTrue(refusal.message.orEmpty().contains("pairing"), refusal.message)
        println("A06 admission: REFUSED by unchanged allowed_modes; not a stand PASS")
    }

    private fun problem(input: Inputs): FlightCrewSchedule {
        // Same configured Jackson path used by FlightIdentityJacksonTest;
        // identity references must bind to the actual deserialized facts.
        val result = mapper.readValue(input.problemBytes, FlightCrewSchedule::class.java)
        assertEquals(1, result.flights.size)
        assertEquals(1, result.employees.size)
        assertEquals(1, result.flightAssignments.size)
        assertSame(result.flights.single(), result.flightAssignments.single().flight)
        assertSame(result.employees.single(), result.flightAssignments.single().employee)
        assertEquals(LocalDateTime.parse("2026-10-01T06:00:00"),
            result.flights.single().departureUTCDateTime)
        assertEquals(LocalDateTime.parse("2026-10-01T21:00:00"),
            result.flights.single().arrivalUTCDateTime)
        return result
    }

    private fun diagnosticScore(input: Inputs, problem: FlightCrewSchedule): Pair<Long, Int> {
        val resolved = RunThresholds.resolveFor(input.pkg, TaskModes.PROFILE_DEFAULT)
        assertEquals(780, resolved.applied.getValue("max_duty_span_min").value)
        RunThresholds.checkFacts(problem, resolved.applied)
        val compiled = LogicCompiler.compile(input.pkg, resolved, TaskModes.PROFILE_DEFAULT)
        LogicCompiler.refuseIfNeeded(compiled)
        val fitted = LogicCompiler.fit(problem, resolved.applied, compiled, "A06 diagnostic score-only")
        LogicCompiler.refuseIfNeeded(fitted)
        RosterLayoverCost.prepare(problem, resolved.applied, packaged = true)
        return RunThresholds.withRunModel(resolved.applied, fitted.plans, packaged = true) {
            val config = SolverConfig()
                .withSolutionClass(FlightCrewSchedule::class.java)
                .withEntityClasses(FlightAssignment::class.java)
                .withConstraintProviderClass(FlightCrewSchedulingConstraintProvider::class.java)
            val factory = SolverFactory.create<FlightCrewSchedule>(config)
                as DefaultSolverFactory<FlightCrewSchedule>
            val director = factory.getScoreDirectorFactory<HardSoftScore>()
                .createScoreDirectorBuilder()
                .withConstraintMatchPolicy(ConstraintMatchPolicy.ENABLED).build()
            try {
                director.setWorkingSolution(problem)
                director.calculateScore()
                val totals = director.constraintMatchTotalMap
                val selected = totals.entries.single { it.key.id() == constraint }
                val result = selected.value.score.hardScore() to
                    selected.value.constraintMatchCount
                println("A06 diagnostic only: $constraint=$result; all contributions=" +
                    totals.entries.joinToString { "${it.key.id()}=${it.value.score}" })
                result
            } finally {
                director.close()
            }
        }
    }

    @Test
    fun diagnosticOnlyNativeDutyAndMinuteBoundaries() = withInputs { input ->
        val expected = input.world.path("expected").path("kotlin_constraint")
        assertEquals(constraint, expected.path("constraint").asText())
        assertEquals(120, expected.path("amount").asInt(-1))
        assertEquals(1, expected.path("matches").asInt(-1))
        assertEquals(780, input.world.path("world").path("params")
            .path("max_duty_duration").asInt(-1))

        // 06:00 -> 21:00 = 900 minutes; native limit 780; 120 * 5 = 600.
        assertEquals(-600L to 1, diagnosticScore(input, problem(input)))

        // Explicit diagnostic derivatives, NOT edits to the primary world or
        // its expectation. Fresh deserialization for each boundary preserves
        // all facts except the one named arrival time.
        val boundary = problem(input)
        boundary.flights.single().arrivalUTCDateTime = LocalDateTime.parse("2026-10-01T19:00:00")
        assertEquals(0L to 0, diagnosticScore(input, boundary))
        val plusMinute = problem(input)
        plusMinute.flights.single().arrivalUTCDateTime = LocalDateTime.parse("2026-10-01T19:01:00")
        assertEquals(-5L to 1, diagnosticScore(input, plusMinute))
    }
}

package org.acme.flighcrewscheduling.domain

import java.time.DayOfWeek

/**
 * Календарное окно дней недели из формы пакета постановки
 * (calendar_window_penalties файла форм порогов) — проблемный факт
 * мягкой семьи механик calendar_windows.
 *
 * Обезличенный шаблон (принцип владельца 2026-08-29): в коде — только
 * механика «действие в окне дней недели»; окно, действие и
 * правило-источник — данными пакета, вес — переопределением весов
 * пакета (канал МУ-03). Родился трафаретом демо сквозного потока
 * 2026-08-29: правило свода «Ночёвки в конце недели».
 *
 * Семантика дня: календарный день НАЧАЛА ночёвки; поле формы
 * tz="base-local" — день по местному времени базовой станции. Мир с
 * единым поясом (нано) делает пересчёт тривиальным; при появлении
 * поясов станций в данных механика расширяется явным шагом, не молча
 * (закрытая семантика формы стережётся приёмником пакета).
 */
data class CalendarWindowRule(
    /** Идентификатор правила свода — трассировка к источнику. */
    val ruleId: String,
    /** Действие окна; сейчас закрытый перечень: layover_penalty. */
    val action: String,
    /** Окно — непустое множество дней недели из закрытого словаря. */
    val days: Set<DayOfWeek>,
)

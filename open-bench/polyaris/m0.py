def build() -> dict:
    # Кодовые имена входных файлов — решение владельца 2026-08-20:
    # ПИ1 (Word), ПЕ1 (Excel), ПР1 (изображение); в именах файлов —
    # латиницей (кириллица в git ломается на чужих машинах).
    sources = [
        {"sid": "S1", "file": "PI1-Pravila-Polyaris.docx",
         "sha256": ""},
        {"sid": "S2", "file": "PE1-Zhurnal-Polyaris.xlsx",
         "sha256": ""},
        {"sid": "S3", "file": "PR1-Pamyatka-Polyaris.jpg",
         "sha256": ""},
    ]
    rules = []
    for rid, title, statement, zone, kind, note in RULES:
        rule = {"id": rid, "title": title, "statement": statement,
                "zone": zone, "kind": kind,
                # Источники дописывает генератор документов: он знает,
                # в какую клаузу какого документа легло правило.
                "sources": []}
        if note:
            rule["note"] = note
        rules.append(rule)
    return {
        "meta": {"customer": "Полярис (PLR)", "mode": 1,
                 "cdpm_version": "m0-polyaris-1",
                 "note": "эталон по построению; документы рендерятся "
                         "из этой модели"},
        "sources": sources,
        "rules": rules,
        "questions": [],
    }


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    m0 = build()
    path = OUT / "M0-model.json"
    path.write_text(json.dumps(m0, ensure_ascii=False, indent=1),
                    encoding="utf-8")
    zones = {}
    for r in m0["rules"]:
        key = (r["zone"], r["kind"])
        zones[key] = zones.get(key, 0) + 1
    print(f"правил: {len(m0['rules'])}; раскладка: "
          + ", ".join(f"{z}/{k}: {n}" for (z, k), n in
                      sorted(zones.items())))
    print(f"записано: {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

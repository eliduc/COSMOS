    # остатка; до нуля жёстких ≈ 8–10) — штат 44 → 54 (+10, верх
    # вилки: цель 0 жёстких с запасом; излишек честно виден балансом
    # и ужимается позже). Базы — пропорционально нагрузке, роли —
    # прежним чередованием (баланс 27/27).
    # ВТОРОЕ решение владельца 2026-08-25 (вечер, подтверждено лично):
    # «добавить 12 человек» — лучший честный прогон −483 при полном

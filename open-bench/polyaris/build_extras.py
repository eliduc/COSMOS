def read_legs() -> list[dict]:
    legs = []
    for f in sorted(glob.glob(str(INST1 / "day_*.csv"))):
        with open(f, encoding="utf-8") as fh:
            r = csv.reader(fh)
            next(r)
            for row in r:
                row = [c.strip() for c in row]
                if len(row) < 7 or not row[0]:
                    continue
                legs.append({
                    "leg": row[0],
                    "dep": CODE.get(row[1], row[1]),
                    "d1": row[2], "t1": row[3],
                    "arr": CODE.get(row[4], row[4]),
                    "d2": row[5], "t2": row[6]})
    legs.sort(key=lambda x: (x["d1"], x["t1"]))
    return legs


def crews() -> list[dict]:
    """Экипажи по численности баз inst1 (listOfBases: 7/20/7)."""

def registry() -> list[dict]:
    out = []
    for did, klass, doc, target, how, payload, expect, rules in DEFECTS:
        if how in ("replace",):
            probe = payload[1]
        elif how == "asis":
            probe = payload
        else:
            probe = payload
        out.append({"id": did, "class": klass, "doc": doc,
                    "target_rule": target, "how": how,
                    "old": (payload[0] if how == "replace" else None),
                    "probe": probe, "expected": expect,
                    "rules": rules})
    return out



"""Единственная реализация настройки консоли для командных инструментов.

Windows по умолчанию отдаёт консоли кодировку cp1252, и `print()` русского
текста роняет процесс `UnicodeEncodeError`. Опасность не в самой ошибке, а
в том, ГДЕ она случается: инструмент успевает записать артефакт, а падает
на печати отчёта — и возвращает код неудачи при удавшейся работе (либо,
что хуже, падает до печати вердикта, который конвейер читал бы).

Раньше каждый инструмент решал это своей копией четырёх строк, и каждый
новый скрипт про них забывал. Здесь одна реализация; тест
`tests/test_cli_console.py` не даёт появиться следующему забывшему.

Зависимость от внешнего `PYTHONUTF8`/`PYTHONIOENCODING` недопустима:
прогон в чистом окружении обязан вести себя так же, как настроенный.
"""
from __future__ import annotations

import sys


def force_utf8_console() -> None:
    """Перевести stdout/stderr в UTF-8. Безопасно вызывать многократно и
    при перенаправленном выводе; на потоке без `reconfigure` (подменённом
    тестом) молча ничего не делает."""
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is None:
            continue
        try:
            reconfigure(encoding="utf-8", errors="replace")
        except (ValueError, OSError):
            # Поток уже закрыт или не поддерживает перенастройку — печать
            # всё равно должна остаться возможной, поэтому молчим.
            pass


def say(text: str, flush: bool = True) -> None:
    """Печать, которая не имеет права уронить своего вызывающего.

    `force_utf8_console` настраивает ТОТ поток, который стоит на месте
    stdout в момент вызова. Фоновый поток печатает позже и не владеет
    этим выбором: под pytest на месте stdout стоит перехватчик без
    `reconfigure` (настройка молча пропускается), и первая же русская
    строка валит поток `UnicodeEncodeError`. Так на прогоне CI 2026-08-16
    падал поток начальной настройки конфигурации — на печати УСПЕШНОГО
    отчёта, то есть работа удавалась, а сообщение о ней убивало поток.

    Поэтому вызывающему даётся печать с запасным путём: при отказе
    кодировки строка выводится с заменой непредставимых символов. Текст
    может пострадать; поток — нет."""
    try:
        print(text, flush=flush)
        return
    except UnicodeEncodeError:
        pass
    enc = getattr(sys.stdout, "encoding", None) or "ascii"
    safe = text.encode(enc, errors="replace").decode(enc, errors="replace")
    try:
        print(safe, flush=flush)
    except (UnicodeEncodeError, ValueError, OSError):
        # Печать невозможна в принципе (поток закрыт). Молчание здесь
        # честнее исключения: сообщать было НЕ о чем — о том, что
        # сообщение не прошло, сообщить всё равно нечем.
        pass

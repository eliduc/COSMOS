"""Личность стенда для тестов: ВЫМЫШЛЕННЫЙ супер-администратор.

Что было. До 10.09.2026 набор был написан против ЛИЧНОЙ почты владельца
машины: `tests/conftest.py` задавал её `CREW_SUPER_ADMIN` на весь прогон,
и около сорока файлов тестов держали тот же адрес литералом. Это тот же
класс зависимости от среды, что порт живой службы и путь машины
разработчика (сторож `tests/test_no_environment_literals.py`): личность
человека оседала в исходниках, в выводе прогонов и в чужих клонах, а
ожидания тестов совпадали с входом по случайности, а не по выводу.

Что стало. Личность объявлена ОДИН раз здесь, вымышленным адресом зоны
`.invalid` — она заведена RFC 6761 (§6.4) ровно для такого случая: имя в
ней гарантированно не разрешается и не может принадлежать никому.
Ожидания тестов строятся из этих же констант, поэтому смена личности —
правка одной строки, а не сорока файлов.

Почему отдельный модуль, а не константа в `tests/conftest.py`: conftest
не импортируют — pytest исполняет его сам, и `from conftest import …`
завёл бы в наборе второй экземпляр модуля со своими побочными
действиями. Отсюда же личность берут зона CDPM и внепроцессные драйверы
(`tests/_replay_driver.py`).

Модуль намеренно БЕЗ импорта приложения: conftest читает его ДО первого
импорта `webapp.*` (модули приложения читают окружение при импорте).
"""

#: Супер-администратор набора. Им `tests/conftest.py` задаёт
#: `CREW_SUPER_ADMIN` на весь прогон, до первого импорта приложения.
ADMIN_EMAIL = "owner@stand.invalid"

#: Слаг папки выгрузок этой личности. Боевой `registry.user_slug`
#: строит его из локальной части адреса через `registry.slugify`;
#: локальная часть выбрана уже пригодной для пути (`[a-z0-9-]`, без
#: заглавных и точек), поэтому `slugify` вернул бы её без изменений — и
#: модуль остаётся без импорта приложения. Меняя ADMIN_EMAIL, держите
#: локальную часть в тех же символах, иначе слаг разойдётся с боевым.
ADMIN_SLUG = ADMIN_EMAIL.split("@", 1)[0]

#: Запись карты владения, дающая личности ИСТОРИЧЕСКИЙ слаг без
#: хвоста-отпечатка: `registry.user_slug` оставляет короткий слаг тому,
#: кто уже владеет выгрузками под ним (grandfathering, аудит P0-03).
#: Без такой записи слаг получил бы отпечаток, и пути выгрузок в тестах
#: разошлись бы с тем, что видит настоящий стенд.
LEGACY_UPLOAD_ID = f"upload-{ADMIN_SLUG}--legacy-seed"

def test_в_манифесте_нет_машинного_признака_смысловой_полноты(tmp_path):
    """Ни одного ключа о смысловой полноте (биекции, прослеживаемости)
    со значением true: машинного доказательства у неё нет."""
    _, _, manifest = _built(tmp_path)
    suspicious = re.compile(
        r"meaning|bijection|traceab|semantic|completeness", re.I)
    bad = []

    def walk(node, path=""):
        if isinstance(node, dict):
            for k, v in node.items():
                here = f"{path}.{k}" if path else str(k)
                if suspicious.search(str(k)) and v is True:
                    bad.append(here)
                walk(v, here)
        elif isinstance(node, list):
            for i, v in enumerate(node):
                walk(v, f"{path}[{i}]")

    walk(manifest)
    assert not bad, f"признак доказанной смысловой полноты: {bad}"



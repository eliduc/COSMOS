def _normalized(path: Path) -> str:
    """Текст носителя без разрывов строк: формула предела в документах
    свёрстана по ширине, в коде — склеена из литералов, и стенд судит
    СЛОВА, а не вёрстку."""
    return re.sub(r"\s+", " ", path.read_text(encoding="utf-8"))


def _text_or_skip(name: str) -> str:
    path, required = SOURCES[name]
    if not path.is_file():
        if required:
            pytest.fail(f"носитель слов пропал: {path}")
        pytest.skip(f"{name}: файла нет в этом срезе ({path.name})")
    return _normalized(path)


def _without_allowed(text: str) -> str:
    """Вырезает условные формы: это законный способ говорить о
    полноте. Наполнитель форм не перешагивает через глагол
    доказанности, поэтому вырезанное не может унести с собою
    заявление (test_белый_список_сам_не_прячет_запретного)."""
    for pattern in ALLOWED:
        text = re.sub(pattern, " ⟨условная форма⟩ ", text, flags=re.I)
    return text


def _segment_before(text: str, start: int) -> str:
    """Начало «единицы речи»: от ближайшего слева конца предложения или
    разделителя ячейки таблицы до самого оборота."""
    bound = max(text.rfind(ch, 0, start) for ch in ".;!?|")
    return text[bound + 1:start]


def _segment_around(text: str, start: int, end: int) -> str:
    """Вся «единица речи», внутри которой стоит оборот: слово
    требования («обязана», «должно») может стоять и в самом обороте."""
    left = max(text.rfind(ch, 0, start) for ch in ".;!?|")
    rights = [i for i in (text.find(ch, end) for ch in ".;!?|") if i >= 0]
    return text[left + 1:min(rights) if rights else len(text)]


def _quoted(text: str, start: int, end: int) -> bool:
    """Оборот целиком внутри кавычек-ёлочек."""
    left = text.rfind("«", 0, start)
    if left < 0:
        return False
    close = text.find("»", left)
    return close >= end


def _is_definition(text: str, m: "re.Match[str]") -> bool:
    """Оборот — ОПРЕДЕЛЕНИЕ (требование к конвейеру) либо ИМЯ/ЦИТАТА, а
    не заявление о доказанном."""
    if DEF_DASH.search(_segment_before(text, m.start())):
        return True
    if DEF_WORDS.search(_segment_around(text, m.start(), m.end())):
        return True
    if _quoted(text, m.start(), m.end()):
        left = text.rfind("«", 0, m.start())
        return bool(CITATION_NEAR.search(text[max(0, left - 200):left]))
    return False


def _statements(text: str) -> list:
    """Безусловные ЗАЯВЛЕНИЯ в тексте (определения и цитаты отсеяны)."""
    text = _without_allowed(text)
    found = []
    for pattern, why in FORBIDDEN:
        for m in re.finditer(pattern, text, re.I):
            if _is_definition(text, m):
                continue
            left = max(0, m.start() - 60)
            found.append(f"«{m.group(0)}» ({why}); рядом: "
                         f"…{text[left:m.end() + 60]}…")
    return found



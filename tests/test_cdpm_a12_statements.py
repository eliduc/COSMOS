def _sp(stem: str) -> str:
    """Основа слова, терпимая к РАЗРЯДКЕ: «д о к а з а н а» — то же
    слово, что «доказана» (пробел между буквами слова не меняет)."""
    return r"\s?".join(re.escape(ch) for ch in stem)


def _any(*stems: str) -> str:
    """Ветка из основ: каждая терпит разрядку и любое окончание."""
    return "(?:" + "|".join(_sp(s) + r"\w*" for s in stems) + ")"


def _verb(*stems: str) -> str:
    """То же для ПРИЧАСТИЙ и глаголов — но без отглагольных
    существительных: «отражение», «сохранением», «исполнения»,
    «обеспечение» — это предмет речи, а не заявление о результате."""
    return "(?:" + "|".join(_sp(s) + r"(?!\s?и\s?[еяюйм])\w*"
                            for s in stems) + ")"


#: Внутри одного предложения и одной ячейки таблицы; кавычки-ёлочки
#: оборот не пересекает (имя и цитата — отдельный предмет).
_BREAK = r"[^.;!?|«»]"


def _fill(n: int) -> str:
    """Наполнитель ЗАПРЕТНОГО оборота: не перешагивает через отрицание
    — иначе «полнота … НЕ доказана» считалась бы заявлением."""
    return r"(?:(?!\bне\b|\bни\b|\bнет\b)" + _BREAK + r"){0," + str(n) + r"}?"


#: Глаголы доказанности: ими объявляют предмет ДОКАЗАННЫМ или
#: ИСПОЛНЕННЫМ. «Обеспечить», «проверяются», «меряют» сюда не входят:
#: это намерение и действие, а не заявление о результате.
_PROVEN = _verb("доказан", "доказыва", "подтверждён", "подтвержден",
                "подтвержда", "обеспечен", "гарантирован", "выполнен",
                "соблюдён", "соблюден", "соблюда", "достигнут",
                "установлен", "исполнен")

#: Глаголы переноса и учёта — ими объявляют, что ВСЁ дошло до свода.
_COVERED = _verb("учтён", "учтен", "покрыт", "отражён", "отражен",
                 "перенесён", "перенесен", "сохранён", "сохранен",
                 "доказан", "взят")

#: Предметы, чья «доказанность» и есть заявление о смысле. Голая
#: «полнота» стоит нарочно: аудит A12 бьёт и по «полнота доказана»
#: без слова «смысловая».
_SUBJECT = "(?:" + "|".join((
    _any("биекци"),
    r"(?:" + _any("двусторонн") + r"\s+)?" + _any("прослеживаемост"),
    _any("смыслов") + r"\s+" + _any("покрыти"),
    _any("полнот"),
    _any("покрыти"),
    r"(?:" + _any("четыре", "все", "оба") + r"\s+)?" + _any("принцип"),
)) + ")"

#: «Все / каждое» + единица СМЫСЛА: перечня обязательств у машины нет,
#: поэтому «все нормы перенесены» — заявление без основания. Клауза,
#: якорь и величина сюда не входят намеренно: это МАШИННЫЕ единицы
#: счёта, их покрытие замок считает и предъявляет — вся находка A12 в
#: том и состоит, что клауза не равна обязательству внутри неё.

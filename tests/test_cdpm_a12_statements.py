def _fill_no_proof(n: int) -> str:
    """Наполнитель УСЛОВНОЙ формы: не перешагивает через глагол
    доказанности, поэтому оговорка не может проглотить заявление."""
    return r"(?:(?!" + _PROVEN + r")" + _BREAK + r"){0," + str(n) + r"}?"


#: БЕЛЫЙ СПИСОК условных форм. Вырезаются из текста ДО поиска запретных
#: оборотов: это и есть разрешённый способ говорить о полноте — назвать
#: её недоказанной. Список закрыт: всякая другая форма судится
#: запретами.
#:
#: НАПОЛНИТЕЛЬ каждой формы не перешагивает через глагол доказанности
#: (_fill_no_proof). Без этого условная форма накрывала бы собою
#: запретное заявление, стоящее в том же предложении, и сторож молчал
#: бы (находка неавтор-ревью 12.09.2026, остаток 1). Глагол внутри
#: формы допустим только там, где он и есть её предмет — «признака,
#: объявляющего смысловую полноту доказанной, НЕ СУЩЕСТВУЕТ».

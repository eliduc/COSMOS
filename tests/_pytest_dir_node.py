# -*- coding: utf-8 -*-
"""Обвязка сборки «один узел папки на прогон» (дефект pytest 9.1).

Правка внесена 09.09.2026 сторонней сессией прямо в tests/conftest.py,
оформлена модулем 10.09.2026: закон живёт здесь, conftest только
регистрирует хук.

ЧТО ЛЕЧИТСЯ. Тесты службы каталога зависели от порядка файлов в
командной строке. Три файла в порядке «подпапка → папка → подпапка»

    pytest tests/catalog_service/test_service_requests.py
           tests/test_template_catalog_reader.py
           tests/catalog_service/test_service_release.py

давали у третьего «fixture 'service' not found», хотя любая пара из них
и полный набор зелёные, а фикстура объявлена в
tests/catalog_service/conftest.py. Тесты после себя ничего не оставляют:
то же воспроизводится с любым файлом из tests/ посередине и без единого
выполненного теста — фикстура невидима уже при сборке.

ПРИЧИНА — устройство pytest 9.1 (журнал изменений 9.1.0, запись
#14004): фикстуры conftest разбираются при сборке узла папки
(Directory) и привязываются к ОБЪЕКТУ этого узла, а не к строке пути.
При этом файл, названный в командной строке прямо, заставляет pytest
собрать его папку заново (совместимость: «файл, названный дважды, не
объединяется»), и у папки tests/ появляется НОВЫЙ узел подпапки
tests/catalog_service/. Её conftest уже разобран для прежнего узла и
второй раз не разбирается — файлы подпапки, названные после файла из
tests/, своих фикстур не видят. В pytest 9.1.1 (последняя на
10.09.2026) починки нет.

КАК ЛЕЧИТСЯ. Хук-обёртка запоминает узел папки в тайнике сессии по паре
«родитель + путь» и на повторный запрос той же папки под тем же
родителем возвращает УЖЕ СОЗДАННЫЙ узел вместо нового. Узел папки —
один на прогон, ровно как pytest сам держит для корневых путей
(path_cache в Session.collect); фикстуры conftest, привязанные к этому
объекту, остаются видимы всем файлам папки в любом порядке.

Пересборка содержимого папки при повторе файла (та самая совместимость)
не трогается: она заводит новые узлы ФАЙЛОВ, их фикстуры разбираются
заново — терять нечего.

Свидетель — tests/test_pytest_dir_node.py: мини-дерево на pytester, без
обвязки отказ воспроизводится, с обвязкой оба порядка зелёные. Красный
отрицательный контроль после обновления pytest значит одно: pytest
починил сборку сам, и обвязку вместе со свидетелем можно снять.
"""
from __future__ import annotations

import pytest

#: Узлы папок этого прогона: (узел-родитель, путь) → узел папки.
_DIRECTORY_NODES = pytest.StashKey[dict]()


@pytest.hookimpl(wrapper=True)
def pytest_collect_directory(path, parent):
    node = yield
    if node is None:
        return None
    nodes = parent.session.stash.setdefault(_DIRECTORY_NODES, {})
    return nodes.setdefault((parent, path), node)

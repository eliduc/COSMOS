"""Declared objective rate must survive the model -> projection comparison.

Offline synthetic catalogue/model only. No solver, model calls, service,
approved-support emulation, release or real corpus. Expectations are the
model's own explicit rate, not values generated by the projection.
"""
import copy

import pytest

from vmp import objective_projection as op
from test_w17b_objective_projection import _catalog, _model


def model_with_rate(catalog, value=7):
    model = _model(catalog)
    model["rules"] = []
    objective = model["objectives"][0]
    objective.pop("criterion")
    objective.update(id="O-ROST", zone="ROSTERING",
                     title="Разброс кредитных часов",
                     statement="Минимизировать разброс кредитных часов",
                     metric="credit_hours_spread", tier=1,
                     rate={"value": value, "per": "час разброса кредитных часов",
                           "as_written": f"{value} за час разброса кредитных часов"})
    return model


@pytest.mark.parametrize("value", [1, 7, 1.5])
def test_declared_rate_roundtrips_without_changing_source(tmp_path, value):
    catalog = _catalog(tmp_path)
    model = model_with_rate(catalog, value)
    before = copy.deepcopy(model)
    projected = op.project(model, catalog)
    assert projected["rostering"]["objectives"][0]["rate"] == model["objectives"][0]["rate"]
    assert op.compare(projected, model, catalog) == []
    assert model == before


@pytest.mark.parametrize("mutation", [
    "value", "bool_value", "fraction", "unit", "quote", "missing_value",
    "missing_rate", "null_rate", "empty_rate", "extra_field",
])
def test_changed_or_lost_rate_is_not_a_matching_projection(tmp_path, mutation):
    catalog = _catalog(tmp_path)
    model = model_with_rate(catalog, 1 if mutation == "bool_value" else 7)
    original = copy.deepcopy(model)
    projected = copy.deepcopy(op.project(model, catalog))
    assert op.compare(projected, model, catalog) == [], "healthy path must reach comparison"
    row = projected["rostering"]["objectives"][0]
    if mutation == "value":
        row["rate"]["value"] = 1
    elif mutation == "bool_value":
        row["rate"]["value"] = True
    elif mutation == "fraction":
        row["rate"]["value"] = 7.5
    elif mutation == "unit":
        row["rate"]["per"] = "минута разброса кредитных часов"
    elif mutation == "quote":
        row["rate"]["as_written"] = "иная исходная ставка"
    elif mutation == "missing_value":
        row["rate"].pop("value")
    elif mutation == "missing_rate":
        row.pop("rate")
    elif mutation == "null_rate":
        row["rate"] = None
    elif mutation == "empty_rate":
        row["rate"] = {}
    else:
        row["rate"]["invented"] = 9
    problems = op.compare(projected, model, catalog)
    assert any(p["code"] == "objective-mismatch"
               and p["where"] == "rostering.objectives[O-ROST].rate"
               for p in problems), problems
    assert model == original, "tampering the presented file must not edit the model oracle"


def test_legacy_absent_rate_stays_valid_but_invented_rate_does_not(tmp_path):
    catalog = _catalog(tmp_path)
    model = model_with_rate(catalog)
    model["objectives"][0].pop("rate")
    projected = op.project(model, catalog)
    assert op.compare(projected, model, catalog) == []
    projected["rostering"]["objectives"][0]["rate"] = {"value": 7}
    problems = op.compare(projected, model, catalog)
    assert any(p["where"] == "rostering.objectives[O-ROST].rate"
               for p in problems), problems
